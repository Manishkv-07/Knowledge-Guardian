export default function Search() {
  const [query, setQuery] = useState('');
  const [results, setResults] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [hasSearched, setHasSearched] = useState(false);

  const handleSearch = async (e) => {
    if (e) e.preventDefault();
    
    // Ignore whitespace-only queries.
    if (!query.trim()) return;

    // Clear previous errors.
    setError(null);
    setLoading(true);
    setHasSearched(true);

    try {
      let data;
      if (USE_MOCK_SEARCH) {
        // Simulate network latency
        await new Promise(resolve => setTimeout(resolve, 800));
        data = { results: MOCK_RESULTS };
      } else {
        // Call the real API service
        data = await searchKnowledge(query.trim());
      }

      // Robustly normalize response payload
      const rawResults = data?.results || (Array.isArray(data) ? data : []);
      const normalized = rawResults.map(result => ({
        chunkId: result.chunk_id || result.id || '',
        text: result.text ?? result.chunk_text ?? result.content ?? result.chunk ?? '',
        filename: result.filename ?? result.file_name ?? result.document_name ?? result.source ?? 'Unknown Document',
        similarity: result.similarity ?? result.score ?? 0,
        chunkNumber: result.chunk_number ?? result.chunk_index ?? result.metadata?.chunk_number,
        totalChunks: result.total_chunks ?? result.metadata?.total_chunks,
        date: result.date ?? result.created_at ?? result.metadata?.date,
        documentId: result.document_id ?? result.metadata?.document_id
      }));

      setResults(normalized);
    } catch (err) {
      console.error("Search failed:", err);
      // Display appropriate error if the request fails
      setError("Something went wrong. Please try again.");
      setResults([]);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="flex-1 flex flex-col space-y-6 overflow-y-auto pr-1">
      <div>
        <h1 className="font-serif text-2xl font-bold text-text-primary tracking-tight">Search Knowledge</h1>
        <p className="text-xs text-text-secondary mt-1">Find what you're looking for in your documents</p>
      </div>

      {/* Search Input Container */}
      <form onSubmit={handleSearch} className="w-full flex gap-3 flex-col sm:flex-row">
        <div className="relative flex-1">
          <input
            id="knowledge-search-input"
            type="text"
            placeholder="Ask a question about your documents..."
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            disabled={loading}
            className="w-full bg-white border border-accent-secondary focus:border-accent-primary focus:ring-1 focus:ring-accent-primary rounded-xl px-4 py-3.5 pl-11 text-sm outline-none transition-all placeholder-text-muted disabled:bg-bg-warm disabled:cursor-not-allowed"
            aria-label="Search documents"
          />
          <svg 
            className="absolute left-4 top-4 h-5 w-5 text-text-muted" 
            fill="none" 
            viewBox="0 0 24 24" 
            stroke="currentColor"
            aria-hidden="true"
          >
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M21 21l-6-6m2-5a7 7 0 11-14 0 7 7 0 0114 0z" />
          </svg>
        </div>
        <button
          type="submit"
          disabled={!query.trim() || loading}
          className="bg-accent-primary hover:bg-accent-tertiary disabled:opacity-40 text-white font-semibold text-sm px-6 py-3.5 rounded-xl transition-all duration-200 shadow-sm flex items-center justify-center gap-2 shrink-0 cursor-pointer disabled:cursor-not-allowed"
        >
          {loading ? (
            <>
              <svg className="animate-spin h-4 w-4 text-white" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24">
                <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4"></circle>
                <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
              </svg>
              <span>Searching...</span>
            </>
          ) : (
            <span>Search</span>
          )}
        </button>
      </form>

      {/* Error state */}
      {error && (
        <div className="bg-status-error/10 border border-status-error/20 text-status-error text-xs px-4 py-3 rounded-lg flex items-center justify-between shadow-sm animate-fade-in">
          <span>{error}</span>
          <button 
            type="button" 
            onClick={() => setError(null)} 
            className="hover:opacity-85 text-base font-bold px-2 py-0.5"
            aria-label="Dismiss error"
          >
            &times;
          </button>
        </div>
      )}

      {/* Results / Empty state / Loading indicator */}
      <div className="space-y-4">
        {loading && (
          <div className="py-12 flex flex-col items-center justify-center text-center space-y-3">
            <svg className="animate-spin h-8 w-8 text-accent-primary" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24">
              <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4"></circle>
              <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
            </svg>
            <p className="text-sm font-medium text-text-secondary">Searching your knowledge base...</p>
          </div>
        )}

        {!loading && hasSearched && results.length > 0 && (
          <div className="space-y-4">
            <div className="text-xs text-text-secondary font-semibold uppercase tracking-wider">
              Found {results.length} {results.length === 1 ? 'result' : 'results'}
            </div>
            <div className="grid grid-cols-1 gap-4">
              {results.map((result, idx) => (
                <SearchResult key={result.chunkId || idx} result={result} />
              ))}
            </div>
          </div>
        )}

        {!loading && hasSearched && results.length === 0 && !error && (
          <div className="h-60 rounded-xl border border-dashed border-accent-secondary bg-white flex flex-col items-center justify-center text-center p-6 space-y-2">
            <svg className="h-10 w-10 text-accent-primary opacity-60" fill="none" viewBox="0 0 24 24" stroke="currentColor" aria-hidden="true">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z" />
            </svg>
            <p className="text-sm font-serif font-semibold text-text-primary">No documents found. Try uploading some documents first.</p>
          </div>
        )}
      </div>
    </div>
  );
}
